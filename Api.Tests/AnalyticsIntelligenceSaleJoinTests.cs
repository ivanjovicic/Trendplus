using Npgsql;
using Xunit;

namespace Api.Tests;

// Regression: the intelligence views joined SalesFacts."Id" (surrogate identity) to
// SalesLineFacts."SaleId" (source sale id); the correct key is SalesFacts."SaleId".
// The probe database seeds headers whose surrogate Id differs from SaleId (and one Id that
// collides with another sale's SaleId); a control database seeds the same sales with
// Id = SaleId. With the correct join both produce identical view output.
public sealed class AnalyticsIntelligenceSaleJoinTests : IClassFixture<PostgresContainerFixture>
{
    private static readonly string[] IntelligenceScripts =
    {
        "Database/Analytics/Intelligence/021_product_demand_signals_v1.sql",
        "Database/Analytics/Intelligence/022_inventory_risk_signals_v1.sql",
        "Database/Analytics/Intelligence/024_trend_momentum_v1.sql",
    };

    private static readonly string[] ViewProbes =
    {
        "SELECT * FROM analytics_intel.vw_product_demand_signals_v1 WHERE article_id = 42 ORDER BY article_id, store_id, date",
        "SELECT * FROM analytics_intel.vw_inventory_risk_signals_v1 WHERE article_id = 42 ORDER BY article_id, date",
        "SELECT * FROM analytics_intel.vw_trend_momentum_v1 WHERE article_id = 42 ORDER BY article_id, signal_date",
    };

    private readonly PostgresContainerFixture _fixture;

    public AnalyticsIntelligenceSaleJoinTests(PostgresContainerFixture fixture)
    {
        _fixture = fixture;
    }

    [Fact]
    public void IntelligenceScripts_JoinSaleHeadersBySourceSaleId()
    {
        foreach (var script in IntelligenceScripts)
        {
            var sql = File.ReadAllText(RepoPath(script));
            Assert.DoesNotContain("sf.\"Id\" = slf.\"SaleId\"", sql, StringComparison.Ordinal);
            Assert.Contains("sf.\"SaleId\" = slf.\"SaleId\"", sql, StringComparison.Ordinal);
        }
    }

    [Fact]
    public async Task IntelligenceViews_AttributeLinesBySourceSaleId_NotSurrogateId()
    {
        if (!_fixture.IsAvailable)
            return;

        var control = await CreateSeededDatabaseAsync("ctl", saleAId: 1000, saleBId: 2000);
        var probe = await CreateSeededDatabaseAsync("prb", saleAId: 1, saleBId: 1000);
        if (control is null || probe is null)
            return;

        // The line belongs to source sale 1000 (store 7, yesterday), never to the header whose
        // surrogate Id happens to be 1000 (store 9, five days ago).
        Assert.Equal(new[] { "7" }, await QueryColumnAsync(probe,
            "SELECT DISTINCT store_id::text FROM analytics_intel.vw_product_demand_signals_v1 WHERE article_id = 42"));
        Assert.Equal(new[] { "0" }, await QueryColumnAsync(probe,
            "SELECT days_since_last_sale::text FROM analytics_intel.vw_product_demand_signals_v1 WHERE article_id = 42 AND date = CURRENT_DATE - 1"));
        Assert.Equal(new[] { "0.000000" }, await QueryColumnAsync(probe,
            "SELECT avg_daily_sales_30d::text FROM analytics_intel.vw_inventory_risk_signals_v1 WHERE article_id = 42 AND date = CURRENT_DATE - 2"));

        foreach (var sql in ViewProbes)
        {
            var expected = await QueryRowsAsync(control, sql);
            Assert.NotEmpty(expected);
            Assert.Equal(expected, await QueryRowsAsync(probe, sql));
        }
    }

    private async Task<string?> CreateSeededDatabaseAsync(string suffix, int saleAId, int saleBId)
    {
        var connectionString = await _fixture.TryCreateDatabaseConnectionStringAsync($"tp_intel_join_{suffix}_{Guid.NewGuid():N}");
        if (string.IsNullOrWhiteSpace(connectionString))
            return null;

        await ExecuteAsync(connectionString, $"""
            CREATE TABLE "ProductsDim" (
                "ProductId" integer NOT NULL,
                "Timestamp" timestamp with time zone NOT NULL,
                "Kolicina" integer NULL,
                "MinimalnaKolicina" integer NULL,
                "PurchasePrice" numeric(18,2) NULL,
                "PurchasePriceRsd" numeric(18,2) NULL
            );
            CREATE TABLE "SalesFacts" (
                "Id" bigint PRIMARY KEY,
                "SaleId" integer NOT NULL UNIQUE,
                "StoreId" integer NOT NULL,
                "SaleTimestampUtc" timestamp with time zone NOT NULL
            );
            CREATE TABLE "SalesLineFacts" (
                "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "SaleId" integer NOT NULL,
                "ProductId" integer NOT NULL,
                "Qty" integer NOT NULL
            );
            CREATE TABLE "InventoryMovementFacts" (
                "ArtikalId" integer NULL,
                "Datum" timestamp with time zone NOT NULL,
                "TipPromene" character varying(100) NOT NULL,
                "Kolicina" integer NULL
            );
            CREATE TABLE "GlobalTrendScores" ("LocalProductId" integer NOT NULL, "FinalGlobalScore" numeric(18,4) NOT NULL);
            CREATE TABLE "TrendHistory" (
                "LocalProductId" integer NOT NULL,
                "FinalGlobalScore" numeric(18,4) NOT NULL,
                "Date" timestamp with time zone NOT NULL,
                "CreatedAt" timestamp with time zone NOT NULL
            );

            INSERT INTO "ProductsDim" ("ProductId", "Timestamp", "Kolicina") VALUES (42, now() - interval '60 days', 10);
            INSERT INTO "SalesFacts" ("Id", "SaleId", "StoreId", "SaleTimestampUtc") VALUES
                ({saleAId}, 1000, 7, ((CURRENT_DATE - 1)::timestamp + interval '10 hours') AT TIME ZONE 'UTC'),
                ({saleBId}, 2000, 9, ((CURRENT_DATE - 5)::timestamp + interval '10 hours') AT TIME ZONE 'UTC');
            INSERT INTO "SalesLineFacts" ("SaleId", "ProductId", "Qty") VALUES (1000, 42, 3);
            """);

        await ExecuteAsync(connectionString, await File.ReadAllTextAsync(RepoPath("Database/Analytics/Intelligence/020_create_intelligence_schema.sql")));
        foreach (var script in IntelligenceScripts)
            await ExecuteAsync(connectionString, await File.ReadAllTextAsync(RepoPath(script)));

        return connectionString;
    }

    private static async Task<List<string>> QueryRowsAsync(string connectionString, string sql)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();
        await using (var setTimeZone = new NpgsqlCommand("SET TIME ZONE 'UTC';", connection))
            await setTimeZone.ExecuteNonQueryAsync();
        await using var command = new NpgsqlCommand(sql, connection);
        await using var reader = await command.ExecuteReaderAsync();
        var rows = new List<string>();
        while (await reader.ReadAsync())
        {
            rows.Add(string.Join("|", Enumerable.Range(0, reader.FieldCount)
                .Select(i => reader.IsDBNull(i) ? "NULL" : Convert.ToString(reader.GetValue(i), System.Globalization.CultureInfo.InvariantCulture))));
        }

        return rows;
    }

    private static Task<List<string>> QueryColumnAsync(string connectionString, string sql) => QueryRowsAsync(connectionString, sql);

    private static async Task ExecuteAsync(string connectionString, string sql)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();
        await using var setTimeZone = new NpgsqlCommand("SET TIME ZONE 'UTC';", connection);
        await setTimeZone.ExecuteNonQueryAsync();
        await using var command = new NpgsqlCommand(sql, connection) { CommandTimeout = 0 };
        await command.ExecuteNonQueryAsync();
    }

    private static string RepoPath(string relativePath)
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null)
        {
            var candidate = Path.Combine(directory.FullName, relativePath.Replace('/', Path.DirectorySeparatorChar));
            if (File.Exists(candidate))
                return candidate;
            directory = directory.Parent;
        }

        throw new FileNotFoundException(relativePath);
    }
}